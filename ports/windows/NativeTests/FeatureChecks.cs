using Cliphoard.Windows;
using System.Text;
using System.Text.Json;
using System.Drawing.Imaging;
internal static class FeatureChecks
{
    internal static void Run()
    {
        int checks = 0;
        void Check(bool value) { ++checks; if (!value) throw new Exception($"Feature check {checks} failed"); }
        Check(ClipboardContent.Tags("#reference, writing, REFERENCE, , " + new string('x', 41)).SequenceEqual(new[] { "reference", "writing" }));
        Check(ClipboardContent.Tags(string.Join(',', Enumerable.Range(0, 30))).Count == 20);
        Check(ClipboardContent.Excluded("KeePassXC", Array.Empty<string>()));
        Check(ClipboardContent.Excluded("notepad", new[] { "NOTEPAD.exe" }));
        Check(!ClipboardContent.Excluded("synthetic-editor", new[] { "note" }));
        using var owner = new Form(); var clipboard = new HistoryClipboard(owner.Handle);
        using var bitmap = new Bitmap(40, 30); using (var g = Graphics.FromImage(bitmap)) g.Clear(Color.MediumSlateBlue);
        using var png = new MemoryStream(); bitmap.Save(png, ImageFormat.Png); byte[] payload = png.ToArray(); Check(ClipboardContent.IsPng(payload));
        byte[] oversized = payload.ToArray(); System.Buffers.Binary.BinaryPrimitives.WriteUInt32BigEndian(oversized.AsSpan(16, 4), 9000); Check(!ClipboardContent.IsPng(oversized)); Check(!ClipboardContent.IsPng(payload[..20]));
        var image = new DataObject(); image.SetData("PNG", new MemoryStream(payload)); Clipboard.SetDataObject(image, true);
        var captured = clipboard.ReadUpdate(); Check(captured is { Kind: "Image", Format: 0, Payload: not null } && captured.Payload.SequenceEqual(payload));
        Check(clipboard.Write(captured!, false)); Check(Clipboard.ContainsData("PNG")); Check(clipboard.ReadUpdate() is null);
        string fragment = "<p>[CLIPHOARD_SYNTHETIC_V1] café &amp; tea<br>second line</p><script>never retained</script>";
        byte[] html = MakeHtml(fragment); Check(ClipboardContent.HtmlText(html) == "[CLIPHOARD_SYNTHETIC_V1] café & tea\nsecond line");
        Check(ClipboardContent.HtmlText("StartFragment:999999\r\nEndFragment:1000000\r\n"u8.ToArray()) is null);
        var markup = new DataObject(); markup.SetData("HTML Format", new MemoryStream(html)); Clipboard.SetDataObject(markup, true);
        var rich = clipboard.ReadUpdate(); Check(rich?.Html is not null && rich.Text.Contains("café & tea")); Check(clipboard.Write(rich!, false)); Check(Clipboard.ContainsData("HTML Format"));
        Check(clipboard.Write(rich!, true)); Check(!Clipboard.ContainsData("HTML Format") && Clipboard.GetText() == rich!.Text);
        foreach (string privacy in new[] { "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "org.nspasteboard.ConcealedType" })
        {
            var privateData = new DataObject(); privateData.SetData(DataFormats.UnicodeText, "[CLIPHOARD_SYNTHETIC_V1] excluded private"); privateData.SetData(privacy, new MemoryStream(new byte[] { 1 })); Clipboard.SetDataObject(privateData, true); Check(clipboard.ReadUpdate() is null);
        }
        string process = System.Diagnostics.Process.GetCurrentProcess().ProcessName;
        var excluded = new HistoryClipboard(owner.Handle, () => new[] { process }); Clipboard.SetText("[CLIPHOARD_SYNTHETIC_V1] excluded app"); Check(excluded.ReadUpdate() is null);
        string directory = Path.Combine(Path.GetTempPath(), "Cliphoard-features-" + Guid.NewGuid().ToString("N"));
        try
        {
            var store = new HistoryStore(directory); rich!.Tags = new() { "reference", "writing" }; store.Add(rich); store.Add(captured!); store.State.ExcludedApps = new() { "synthetic-editor" }; store.State.SoundEnabled = true; store.Save();
            var loaded = new HistoryStore(directory); Check(loaded.Writable && loaded.State.Items.Count == 2 && loaded.State.SoundEnabled && loaded.State.ExcludedApps.SequenceEqual(new[] { "synthetic-editor" }));
            var loadedRich = loaded.State.Items.Single(i => i.Html is not null); Check(loadedRich.Tags.SequenceEqual(new[] { "reference", "writing" }));
            loaded.Add(new() { Text = loadedRich.Text, Html = loadedRich.Html }); Check(loaded.State.Items[0].Tags.SequenceEqual(loadedRich.Tags));
            var loadedPng = loaded.State.Items.Single(i => i.Format == 0); Check(loadedPng.Payload!.SequenceEqual(payload));
        }
        finally { Directory.Delete(directory, true); }
        Console.WriteLine(JsonSerializer.Serialize(new { feature_checks = checks, status = "passed", data = "generated synthetic only" }));
    }
    internal static byte[] MakeHtml(string fragment)
    {
        const string template = "Version:1.0\r\nStartHTML:{0:D10}\r\nEndHTML:{1:D10}\r\nStartFragment:{2:D10}\r\nEndFragment:{3:D10}\r\n";
        const string before = "<html><body><!--StartFragment-->", after = "<!--EndFragment--></body></html>";
        int header = Encoding.UTF8.GetByteCount(string.Format(template, 0, 0, 0, 0)), start = header + Encoding.UTF8.GetByteCount(before), end = start + Encoding.UTF8.GetByteCount(fragment);
        return Encoding.UTF8.GetBytes(string.Format(template, header, end + Encoding.UTF8.GetByteCount(after), start, end) + before + fragment + after + "\0");
    }
}
